#!/usr/bin/env python3
"""Build Freeze Guard as a single executable file.

Freeze Guard is Linux only (it reads /proc/pressure and manages systemd units), so there is one target:

    ./build-exe.py      -> dist/freeze-guard-linux-<arch>-<version>-build<build>

Run it on the oldest system the file is meant for: it runs on every Linux with
the same or a newer glibc, never on an older one.

What it does:

1. creates a private build environment in ``build/exe/venv`` without the system
   packages, so nothing the build machine happens to have ends up in the file,
   with the system's PyGObject linked in, which pip cannot install,
2. installs PyInstaller,
3. writes the VERSION file from the commit history (what ``version.py --write``
   does) and stages it as data together with ``run-monitor.py``, which the window loads by path,
4. runs PyInstaller and checks that the result starts and answers ``--version``
   without a display.

Only the dashboard and the recorder are in the file. The protection itself (zram,
earlyoom, kernel settings, the daemon and the systemd units) is installed from a checkout with
``sudo ./install.sh``; a single file cannot do that. Build machine: ``sudo apt install
python3-venv python3-tk python3-gi gir1.2-gtk-3.0`` (plus ``gir1.2-xapp-1.0`` and
``gir1.2-ayatanaappindicator3-0.1`` for the tray icon), run with the system Python, because only
it can see PyGObject.

Options:

    --clean     rebuild the build environment from scratch
    --keep-env  reuse the build environment without updating its packages

Author:  Joachim Ruf, Loresoft.de
"""

from __future__ import annotations

import argparse
import importlib.metadata
import importlib.util
import os
import platform
import shutil
import subprocess
import sys
import venv
from pathlib import Path
from typing import List, Optional

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

import version  # noqa: E402


APP_SLUG = "freeze-guard"
APP_TITLE = "Freeze Guard"
ENTRY_SCRIPT = "run.py"

BUILD_DIR = ROOT / "build" / "exe"
VENV_DIR = BUILD_DIR / "venv"
STAGE_DIR = BUILD_DIR / "stage"
WORK_DIR = BUILD_DIR / "work"
SPEC_FILE = WORK_DIR / (APP_SLUG + ".spec")
DIST_DIR = ROOT / "dist"

PYINSTALLER_SPEC = "pyinstaller>=6.9"

#: Pip packages the program imports besides the standard library.
RUNTIME_PACKAGES: List[str] = []

#: Read-only files the program opens at run time, relative to the project root. They are
#: staged in the checkout's layout and unpacked as ``sys._MEIPASS``.
DATA_FILES: List[str] = ['run-monitor.py', 'resources']

#: Packages whose modules are all carried, whether or not PyInstaller sees them
#: imported. Everything else is found by following the imports of the entry script.
SUBMODULE_PACKAGES: List[str] = []

#: Modules imported only in ways PyInstaller cannot follow (inside functions, by name, by path).
HIDDEN_IMPORTS: List[str] = ['bootstrap_ui', 'fg_instance', 'fg_platform', 'version', 'exe_support', 'curses', 'tkinter', 'tkinter.scrolledtext']

#: The GTK modules the program loads lazily or by name.
GI_MODULES: List[str] = ['gi.repository.Gtk', 'gi.repository.Gdk', 'gi.repository.Gio', 'gi.repository.GLib', 'gi.repository.Pango', 'gi.repository.XApp', 'gi.repository.AyatanaAppIndicator3']

#: GTK's share data, limited to what the program needs. Unlimited, PyInstaller packs every
#: icon and theme of the build machine (467 MB instead of 70 MB).
GTK_HOOK_CONFIG = {
    "gi": {
        "icons": ['Adwaita'],
        "themes": ['Adwaita'],
        "languages": ["de", "en"],
        "module-versions": {'Gtk': '3.0', 'Gdk': '3.0', 'XApp': '1.0', 'AyatanaAppIndicator3': '0.1'},
    },
}

SPEC_TEMPLATE = '''# Generated by build-exe.py - edit that script, not this file.
from PyInstaller.utils.hooks import collect_submodules

datas = {datas!r}
hiddenimports = {hidden!r}
for package in {submodules!r}:
    hiddenimports += collect_submodules(package)

a = Analysis(
    [{entry!r}],
    pathex=[{root!r}],
    binaries=[],
    datas=datas,
    hiddenimports=hiddenimports,
    hookspath=[],
    hooksconfig={hooksconfig!r},
    runtime_hooks=[],
    excludes=[],
    noarchive=False,
)
pyz = PYZ(a.pure)
exe = EXE(
    pyz,
    a.scripts,
    a.binaries,
    a.datas,
    [],
    name={name!r},
    debug=False,
    strip=False,
    upx=False,
    runtime_tmpdir=None,
    console={console!r},
    icon=None,
)
'''

CONSOLE = False


def info(message: str) -> None:
    """Print a progress line."""
    print("[build-exe] " + message, flush=True)


def fail(message: str) -> None:
    """Print an error and stop with exit code 1."""
    print("[build-exe] ERROR: " + message, file=sys.stderr, flush=True)
    sys.exit(1)


def executable_name(name: str, build: str) -> str:
    """
    Return the file name of the executable for this machine and version.

    The version is part of the name so a downloaded file says which one it is.
    The release workflow and the Loresoft site rely on this exact form.

    :param name: ``major.minor.patch``.
    :param build: The build number.
    :return: For example ``freeze-guard-linux-x86_64-0.2.5-build14``.
    """
    machine = platform.machine().lower()
    machine = {"amd64": "x86_64", "x64": "x86_64", "arm64": "aarch64"}.get(machine, machine)
    return "{0}-linux-{1}-{2}-build{3}".format(APP_SLUG, machine, name, build)


def venv_python() -> Path:
    """Return the interpreter of the build environment."""
    return VENV_DIR / "bin" / "python"


def run(command: List[object], **kwargs) -> None:
    """Run a command and stop the build when it fails."""
    info("$ " + " ".join(str(part) for part in command))
    completed = subprocess.run([str(part) for part in command], **kwargs)
    if completed.returncode != 0:
        fail("command failed with exit code {0}".format(completed.returncode))


def check_build_host() -> None:
    """Stop early when this machine cannot produce a working program."""
    if not sys.platform.startswith("linux"):
        fail(APP_TITLE + " is Linux only; build it on Linux.")
    if sys.version_info < (3, 9):
        fail("building needs Python 3.9 or newer.")
    try:
        import ensurepip  # noqa: F401
    except ImportError:
        fail("venv/ensurepip is missing - sudo apt install python3-venv")
    try:
        import tkinter  # noqa: F401
    except ImportError:
        fail("tkinter is missing - sudo apt install python3-tk")
    if system_gi() is None:
        fail("PyGObject is missing - sudo apt install python3-gi gir1.2-gtk-3.0")


def prepare_venv(clean: bool, keep: bool) -> None:
    """
    Create or refresh the build environment.

    It is created without the system packages, so nothing the build machine
    happens to have installed (numpy, lxml, ...) ends up in the executable.
    """
    if clean and VENV_DIR.exists():
        info("Removing the old build environment ...")
        shutil.rmtree(str(VENV_DIR))
    if not venv_python().exists():
        info("Creating the build environment in {0} ...".format(VENV_DIR))
        venv.EnvBuilder(with_pip=True).create(str(VENV_DIR))
    elif keep:
        info("Reusing the build environment as it is.")
        return
    pip = [venv_python(), "-m", "pip", "install", "--upgrade", "--disable-pip-version-check", "--no-cache-dir"]
    run(pip + ["pip"])
    run(pip + [PYINSTALLER_SPEC] + RUNTIME_PACKAGES)
    gi = system_gi()
    if gi is None:
        fail("PyGObject is missing - sudo apt install python3-gi gir1.2-gtk-3.0")
    # The package and its metadata: PyInstaller's hook reads the version.
    sources = [gi]
    try:
        sources.append(Path(str(importlib.metadata.distribution("pygobject")._path)))
    except (importlib.metadata.PackageNotFoundError, AttributeError):
        info("WARNING: no PyGObject metadata found - PyInstaller may reject the build.")
    site = venv_site_packages()
    for source in sources:
        link = site / source.name
        if not link.exists():
            info("Linking the system {0} into the build environment ...".format(source.name))
            link.symlink_to(source, target_is_directory=True)


def system_gi() -> Optional[Path]:
    """Return the PyGObject package of this interpreter, or ``None``."""
    spec = importlib.util.find_spec("gi")
    if spec is None or not spec.submodule_search_locations:
        return None
    return Path(list(spec.submodule_search_locations)[0])


def venv_site_packages() -> Path:
    """Return the ``site-packages`` directory of the build environment."""
    completed = subprocess.run(
        [str(venv_python()), "-c", "import sysconfig; print(sysconfig.get_paths()['purelib'])"],
        stdout=subprocess.PIPE, check=True)
    return Path(completed.stdout.decode().strip())


def write_version() -> version.Version:
    """
    Write the VERSION file from the history and return what it says.

    The executable reads only this file: it has no history to derive from.
    """
    found = version.write_file() or version.from_file(ROOT)
    if found is None or not found.is_known or not found.build:
        fail("no version: neither a git history nor a VERSION file (clone with full history).")
    return found


def stage_data(found: version.Version) -> Path:
    """
    Copy the read-only files the executable carries, in the checkout's layout.

    :param found: The version to carry as the VERSION file.

    :return: The staged root, unpacked as ``sys._MEIPASS`` at run time.
    """
    if STAGE_DIR.exists():
        shutil.rmtree(str(STAGE_DIR))
    STAGE_DIR.mkdir(parents=True)
    count = 0
    for relative in DATA_FILES:
        source = ROOT / relative
        if source.is_dir():
            shutil.copytree(str(source), str(STAGE_DIR / relative),
                            ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        elif source.is_file():
            destination = STAGE_DIR / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(str(source), str(destination))
        else:
            fail("{0} is missing".format(source))
        count += 1
    (STAGE_DIR / version.VERSION_FILE.name).write_text(found.line() + "\n", encoding="utf-8")
    info("Staged {0} data files and VERSION {1}.".format(count, found.label))
    return STAGE_DIR


def spec_text(staged: Path, name: str) -> str:
    """
    Return the PyInstaller spec file.

    :param staged: The staged root from :func:`stage_data`.
    :param name: The file name of the executable.
    :return: The content of the spec file.
    """
    return SPEC_TEMPLATE.format(
        datas=[(str(staged), ".")],
        hidden=HIDDEN_IMPORTS + GI_MODULES,
        submodules=SUBMODULE_PACKAGES,
        entry=str(ROOT / ENTRY_SCRIPT),
        root=str(ROOT),
        hooksconfig=GTK_HOOK_CONFIG,
        name=name,
        console=CONSOLE,
    )


def smoke_test(executable: Path, found: version.Version) -> None:
    """Start the result once and make sure it answers with its version, without a display."""
    info("Starting {0} --version ...".format(executable.name))
    environment = {key: value for key, value in os.environ.items()
                   if key not in ("DISPLAY", "WAYLAND_DISPLAY", version.ENVIRONMENT_VARIABLE)}
    completed = subprocess.run([str(executable), "--version"], stdout=subprocess.PIPE,
                               stderr=subprocess.STDOUT, timeout=300, env=environment)
    output = completed.stdout.decode("utf-8", errors="replace").strip()
    if completed.returncode != 0:
        fail("the executable did not start (exit code {0}):\n{1}".format(completed.returncode, output))
    expected = "{0} ({1})".format(found.name, found.build)
    if expected not in output:
        fail("the executable reports {0!r}, expected {1}".format(output, expected))
    info("OK: " + output)


def main() -> int:
    """Run the whole build."""
    parser = argparse.ArgumentParser(description="Build " + APP_TITLE + " as a single executable file (Linux only).")
    parser.add_argument("--clean", action="store_true", help="rebuild the build environment from scratch")
    parser.add_argument("--keep-env", action="store_true",
                        help="reuse the build environment without updating its packages")
    args = parser.parse_args()

    check_build_host()
    found = write_version()
    name = executable_name(found.name, found.build)
    info("{0} {1} as {2}".format(APP_TITLE, found.label, name))
    prepare_venv(clean=args.clean, keep=args.keep_env)
    staged = stage_data(found)
    WORK_DIR.mkdir(parents=True, exist_ok=True)
    SPEC_FILE.write_text(spec_text(staged, name), encoding="utf-8")
    run([venv_python(), "-m", "PyInstaller", "--noconfirm", "--clean",
         "--distpath", DIST_DIR, "--workpath", WORK_DIR, SPEC_FILE], cwd=str(ROOT))

    result = DIST_DIR / name
    if not result.is_file():
        fail("PyInstaller finished but {0} is missing".format(result))
    smoke_test(result, found)
    info("Done: {0} ({1:.1f} MB)".format(result, result.stat().st_size / 1048576))
    return 0


if __name__ == "__main__":
    sys.exit(main())
